const playerSpriteCache = new Map<string, HTMLCanvasElement>();
const flippedSpriteCache = new Map<string, HTMLCanvasElement>();

function flipHorizontalCached(key: string, src: HTMLCanvasElement): HTMLCanvasElement {
  const existing = flippedSpriteCache.get(key);
  if (existing) return existing;
  const c = makeCanvas(src.width, src.height);
  const ctx = c.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  ctx.translate(src.width, 0);
  ctx.scale(-1, 1);
  ctx.drawImage(src, 0, 0);
  flippedSpriteCache.set(key, c);
  return c;
}

export function getPlayerSpriteCanvas(
  player: PlayerCustomization,
  striking = false,
  action?: PlayerAction,
  frame = 0,
  facing: 1 | -1 = 1,
): HTMLCanvasElement {
  const effectiveAction: PlayerAction = action ?? (striking ? 'strike' : 'idle');
  const sheetPlayer = getPlayerSheetSprite(player, effectiveAction, frame, 72);
  if (sheetPlayer) {
    if (facing === -1) {
      const fKey = `${player.gender}_${player.skinToneIndex}_${player.hairColorIndex}_${player.outfitColorIndex}_${effectiveAction}_${frame}_flip`;
      return flipHorizontalCached(fKey, sheetPlayer);
    }
    return sheetPlayer;
  }

  const key = `${player.gender}_${player.skinToneIndex}_${player.hairColorIndex}_${player.outfitColorIndex}_${striking ? 1 : 0}`;
  const cached = playerSpriteCache.get(key);
  if (cached) return cached;

  const skin = SKIN_TONES[player.skinToneIndex] ?? SKIN_TONES[0];
  const hair = HAIR_COLORS[player.hairColorIndex] ?? HAIR_COLORS[0];
  const outfit = OUTFIT_COLORS[player.outfitColorIndex] ?? OUTFIT_COLORS[0];

  const c = makeCanvas(32, 32);
  const ctx = c.getContext('2d')!;

  drawIndexedMap(ctx, BODY_BASE_MAP, {
    o: '#120c0a',
    S: skin.hex,
    s: skin.shadow,
    e: '#1e1b18',
    T: outfit.main,
    A: outfit.trim,
    b: '#3b2416',
    P: '#2c2930',
    B: '#4a3222',
  });

  const hairMap = player.gender === 'female' ? HAIR_FEMALE_MAP : HAIR_MALE_MAP;
  drawIndexedMap(ctx, hairMap, {
    o: '#120c0a',
    H: hair.hex,
    h: hair.highlight,
  });

  const hammerMap = striking ? HAMMER_STRIKE_MAP : HAMMER_IDLE_MAP;
  drawIndexedMap(
    ctx,
    hammerMap,
    {
      o: '#120c0a',
      M: '#94a3b8',
      m: '#475569',
      W: '#7c4d25',
    },
    0,
    striking ? 11 : 7,
  );

  playerSpriteCache.set(key, c);
  return c;
}

