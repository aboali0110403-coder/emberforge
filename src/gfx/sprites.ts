const materialIconCache = new Map<string, HTMLCanvasElement>();

export function getMaterialIconCanvas(materialId: string): HTMLCanvasElement {
  const mat = MATERIAL_BY_ID[materialId];
  if (mat) {
    const sheetIcon = getMaterialSheetSprite(mat.id, mat.shape, mat.colors, 44);
    if (sheetIcon) return sheetIcon;
  }

  const cached = materialIconCache.get(materialId);
  if (cached) return cached;

  const c = makeCanvas(16, 16);
  const ctx = c.getContext('2d')!;
  if (mat) {
    drawIndexedMap(ctx, MATERIAL_SHAPE_MAPS[mat.shape], {
      o: '#120c0a',
      '1': mat.colors[0],
      '2': mat.colors[1],
      '3': mat.colors[2],
    });
  }
  materialIconCache.set(materialId, c);
  return c;
}

