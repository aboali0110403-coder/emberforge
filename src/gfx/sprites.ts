const weaponSpriteCache = new Map<string, HTMLCanvasElement>();

export function getWeaponSpriteCanvas(weapon: WeaponInstance): HTMLCanvasElement {
  let highestRarity: RarityId = 'common';
  let bestIdx = 0;
  for (const part of Object.values(weapon.parts)) {
    const idx = RARITY_ORDER.indexOf(part.rarity);
    if (idx > bestIdx) {
      bestIdx = idx;
      highestRarity = part.rarity;
    }
  }
  const sheetWeapon = getWeaponSheetSprite(weapon.type, highestRarity, weapon.level, 80);
  if (sheetWeapon) return sheetWeapon;

  const partSig = Object.entries(weapon.parts)
    .map(([k, v]) => `${k}:${v.rarity}`)
    .sort()
    .join('|');
  const key = `${weapon.type}_${partSig}`;
  const cached = weaponSpriteCache.get(key);
  if (cached) return cached;

  const c = makeCanvas(32, 32);
  const ctx = c.getContext('2d')!;
  const layers = WEAPON_PART_LAYERS[weapon.type];

  for (const layer of layers) {
    const partState = weapon.parts[layer.partKey];
    const rarity: RarityId = partState?.rarity ?? 'common';
    const pal = PART_RARITY_PALETTES[rarity];
    drawIndexedMap(ctx, layer.rows, {
      o: '#120c0a',
      '1': pal.dark,
      '2': pal.mid,
      '3': pal.light,
    });
  }

  weaponSpriteCache.set(key, c);
  return c;
}

const heatedWeaponCache = new Map<string, HTMLCanvasElement>();

/**
 * Returns a cached weapon canvas tinted for forge heat stage or quenched steel.
 * Uses source-atop offscreen compositing once per cache key to avoid per-frame pixel scans.
 */
export function getHeatedWeaponCanvas(
  weapon: WeaponInstance,
  bucket: 'cold' | 'warm' | 'hot' | 'overheat' | 'quenched',
): HTMLCanvasElement {
  const base = getWeaponSpriteCanvas(weapon);
  if (bucket === 'cold') return base;

  let highestRarity: RarityId = 'common';
  let bestIdx = 0;
  for (const part of Object.values(weapon.parts)) {
    const idx = RARITY_ORDER.indexOf(part.rarity);
    if (idx > bestIdx) {
      bestIdx = idx;
      highestRarity = part.rarity;
    }
  }
  const tierBucket = Math.max(Math.min(4, Math.floor(Math.max(0, weapon.level - 1) / 4)), bestIdx);
  const key = `${weapon.type}_${tierBucket}_${bucket}_${base.width}`;
  const cached = heatedWeaponCache.get(key);
  if (cached) return cached;

  const c = makeCanvas(base.width, base.height);
  const ctx = c.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(base, 0, 0);
  ctx.globalCompositeOperation = 'source-atop';
  if (bucket === 'warm') {
    ctx.fillStyle = 'rgba(220, 38, 38, 0.36)';
  } else if (bucket === 'hot') {
    ctx.fillStyle = 'rgba(249, 115, 22, 0.56)';
  } else if (bucket === 'overheat') {
    ctx.fillStyle = 'rgba(254, 240, 138, 0.72)';
  } else {
    ctx.fillStyle = 'rgba(56, 189, 248, 0.34)';
  }
  ctx.fillRect(0, 0, c.width, c.height);
  ctx.globalCompositeOperation = 'source-over';

  heatedWeaponCache.set(key, c);
  return c;
}
